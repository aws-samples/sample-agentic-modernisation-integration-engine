"""AWS DMS artifacts derived from a discovery report.

The application only *generates* these files. Deploying the CloudFormation template creates billable
resources and is a human decision.

Design choices:
- The target schema is created from the reviewed schema DDL and approved conversions, so the task
  uses ``TargetTablePrepMode: DO_NOTHING`` and DMS never creates tables itself.
- LOB handling follows the discovered column types: any MAX/LOB column selects limited LOB mode with
  a 64 KB inline size; there is no LOB column → LOB support off.
- Endpoint credentials come from Secrets Manager secrets in the DMS format (username, password, host,
  port). An RDS-managed master secret has no host/port, so a separate DMS secret is required.
"""

from __future__ import annotations

import io
import json
import zipfile

from services.db_conversion.schema_ddl import render_schema_sql

_LOB_TYPES = {"text", "ntext", "image", "xml"}
_DMS_UNSUPPORTED_TYPES = {
    "geography",
    "geometry",
    "hierarchyid",
    "sql_variant",
    "timestamp",
    "rowversion",
}


def _tables(report: dict) -> list[dict]:
    return [o for o in report["objects"] if o["type"] == "table"]


def _has_lob(report: dict) -> bool:
    for t in _tables(report):
        for c in t["columns"]:
            base = c["sql_type"].split("(")[0]
            if "(max)" in c["sql_type"] or base in _LOB_TYPES:
                return True
    return False


def table_mappings(report: dict) -> dict:
    rules = []
    schemas = sorted({t["schema"] for t in _tables(report)})
    for n, schema in enumerate(schemas, start=1):
        rules.append(
            {
                "rule-type": "selection",
                "rule-id": str(n),
                "rule-name": f"include-{schema}",
                "object-locator": {"schema-name": schema, "table-name": "%"},
                "rule-action": "include",
            }
        )
    # Memory-optimised and temporal history tables stay out of the CDC scope by default; they are
    # handled by the reviewed design (see README).
    n = len(rules)
    for t in _tables(report):
        if "memory_optimized" in t.get("subtype", ""):
            n += 1
            rules.append(
                {
                    "rule-type": "selection",
                    "rule-id": str(n),
                    "rule-name": f"exclude-memopt-{t['schema']}-{t['name']}"[:255],
                    "object-locator": {
                        "schema-name": t["schema"],
                        "table-name": t["name"],
                    },
                    "rule-action": "exclude",
                }
            )
    return {"rules": rules}


def task_settings(report: dict) -> dict:
    lob = _has_lob(report)
    return {
        "TargetMetadata": {
            "SupportLobs": lob,
            "FullLobMode": False,
            "LimitedSizeLobMode": lob,
            "LobMaxSize": 64 if lob else 0,
            "InlineLobMaxSize": 0,
            "BatchApplyEnabled": False,
        },
        "FullLoadSettings": {
            "TargetTablePrepMode": "DO_NOTHING",
            "CreatePkAfterFullLoad": False,
            "StopTaskCachedChangesApplied": False,
            "StopTaskCachedChangesNotApplied": False,
            "MaxFullLoadSubTasks": 8,
            "CommitRate": 10000,
        },
        "ValidationSettings": {
            "EnableValidation": True,
            "ValidationMode": "ROW_LEVEL",
            "ThreadCount": 5,
            "FailureMaxCount": 10000,
            "HandleCollationDiff": True,
        },
        "Logging": {
            "EnableLogging": True,
            "LogComponents": [
                {"Id": "SOURCE_UNLOAD", "Severity": "LOGGER_SEVERITY_DEFAULT"},
                {"Id": "SOURCE_CAPTURE", "Severity": "LOGGER_SEVERITY_DEFAULT"},
                {"Id": "TARGET_LOAD", "Severity": "LOGGER_SEVERITY_DEFAULT"},
                {"Id": "TARGET_APPLY", "Severity": "LOGGER_SEVERITY_DEFAULT"},
                {"Id": "VALIDATOR_EXT", "Severity": "LOGGER_SEVERITY_DEFAULT"},
            ],
        },
        "ErrorBehavior": {
            "DataErrorPolicy": "LOG_ERROR",
            "TableErrorPolicy": "SUSPEND_TABLE",
            "ApplyErrorDeletePolicy": "LOG_ERROR",
            "ApplyErrorInsertPolicy": "LOG_ERROR",
            "ApplyErrorUpdatePolicy": "LOG_ERROR",
        },
    }


