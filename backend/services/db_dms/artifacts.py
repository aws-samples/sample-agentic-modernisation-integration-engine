def readme(report: dict) -> str:
    tables = _tables(report)
    no_pk = [f"{t['schema']}.{t['name']}" for t in tables if not t.get("primary_key")]
    memopt = [
        f"{t['schema']}.{t['name']}"
        for t in tables
        if "memory_optimized" in t.get("subtype", "")
    ]
    temporal = [
        f"{t['schema']}.{t['name']}"
        for t in tables
        if "temporal" in t.get("subtype", "")
    ]
    unsupported = [
        f"{t['schema']}.{t['name']}.{c['name']} ({c['sql_type']})"
        for t in tables
        for c in t["columns"]
        if c["sql_type"].split("(")[0] in _DMS_UNSUPPORTED_TYPES
    ]
    computed = [
        f"{t['schema']}.{t['name']}.{c['name']}"
        for t in tables
        for c in t["columns"]
        if c.get("computed")
    ]

    def bullets(items: list[str], empty: str) -> str:
        return "\n".join(f"- `{i}`" for i in items) if items else f"- {empty}"

    return f"""# AWS DMS artifacts: SQL Server → Aurora MySQL

Generated from discovery `{report['discovery_id']}`. These files are **not deployed** by AMIE.

| File | Purpose |
|---|---|
| `schema.sql` | Target MySQL DDL (deterministic). Create it, plus approved conversions, before the DMS task runs. |
| `table-mappings.json` | One selection rule per schema; memory-optimised tables excluded. |
| `task-settings.json` | `TargetTablePrepMode: DO_NOTHING`, LOB mode from discovered types, row-level validation on. |
| `cloudformation-dms.yaml` | Replication instance, SQL Server and Aurora MySQL endpoints, full-load + CDC task, optional DMS Schema Conversion project. |

## Order of work

1. Create the Aurora MySQL 3 cluster and apply `schema.sql` and the approved `conversions.sql`.
2. Prepare the source for CDC (below).
3. Create Secrets Manager secrets **in DMS format** (`username`, `password`, `host`, `port`) for both
   databases. An RDS-managed master secret has no host/port and cannot be used directly.
4. Deploy `cloudformation-dms.yaml`, review it first; it creates billable resources.
5. Start the task, then run the AMIE validation harness against the target.

## Source prerequisites for CDC

On RDS for SQL Server:

```sql
EXEC msdb.dbo.rds_cdc_enable_db '{report.get('database_name') or 'WideWorldImporters'}';
-- then per table, for example:
EXEC sys.sp_cdc_enable_table @source_schema = N'Sales', @source_name = N'Orders', @role_name = NULL;
```

Set the backup retention period to at least one day so transaction-log backups exist.

## Tables without a primary key ({len(no_pk)})

DMS CDC cannot capture updates and deletes for these; add a key or use full load only.

{bullets(no_pk, "None.")}

## Memory-optimised tables ({len(memopt)})

Excluded in `table-mappings.json`: DMS does not capture changes from memory-optimised tables.

{bullets(memopt, "None.")}

## Temporal tables ({len(temporal)})

DMS migrates the current table and the history table as ordinary tables. History maintenance on the
target comes from the reviewed conversion (triggers), not from DMS.

{bullets(temporal, "None.")}

## Columns DMS cannot migrate as-is ({len(unsupported)})

{bullets(unsupported, "None.")}

## Computed columns ({len(computed)})

The source values are migrated into ordinary columns unless the target defines them as generated
columns, in which case exclude them with a transformation rule.

{bullets(computed, "None.")}
"""


def build_zip(report: dict) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("README.md", readme(report))
        zf.writestr("schema.sql", render_schema_sql(report))
        zf.writestr(
            "table-mappings.json", json.dumps(table_mappings(report), indent=2) + "\n"
        )
        zf.writestr(
            "task-settings.json", json.dumps(task_settings(report), indent=2) + "\n"
        )
        zf.writestr("cloudformation-dms.yaml", cloudformation_template(report))
    return buf.getvalue()
